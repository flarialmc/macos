__declspec(dllexport) HRESULT QueryApiImpl(const GUID* prov, const GUID* iid, void** out) {
  char p[40], i[40]; guidstr(prov, p); guidstr(iid, i);
  if (prov->Data1 != 0x073b7dcb && xgr_trace_on()) xgr_log("QueryApiImpl prov=%s iid=%s caller=%p", p, i, __builtin_return_address(0));
  Obj* o = (Obj*)HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, sizeof(Obj));
  o->vtbl = g_vtbl; o->prov = *prov; o->iid = *iid; o->ref = 1; *out = o; return S_OK;
}
