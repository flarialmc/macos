static const Impl* g_tables[] = { g_networking_impls, g_xuser_impls, g_system_impls, g_taskqueue_impls, 0 };
static impl_fn find_impl(Obj* o, int n) {
  for (int t = 0; g_tables[t]; t++)
    for (int k = 0; g_tables[t][k].fn; k++)
      if (g_tables[t][k].prov1 == o->prov.Data1 && g_tables[t][k].slot == n) return g_tables[t][k].fn;
  return 0;
}
